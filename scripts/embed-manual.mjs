#!/usr/bin/env node
// Regenerates src/skill/manual-text.ts from src/skill/agentchat.skill.md.
//
// The manual is https://agentchat.me/skill.md, bundled verbatim so every
// doorbell built on this engine places the same text. The generated module is
// committed; tests/manual.test.ts fails when the two files drift, so a refresh
// is: replace agentchat.skill.md, run this script, commit both.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = readFileSync(join(root, 'src', 'skill', 'agentchat.skill.md'), 'utf-8')
const out = [
  '// GENERATED by scripts/embed-manual.mjs from src/skill/agentchat.skill.md — do not edit.',
  '// The manual is https://agentchat.me/skill.md, bundled verbatim; tests/manual.test.ts',
  '// keeps this module and the markdown file in lockstep.',
  `export const MANUAL_TEXT: string = ${JSON.stringify(source)}`,
  '',
].join('\n')
writeFileSync(join(root, 'src', 'skill', 'manual-text.ts'), out)
console.log(`wrote src/skill/manual-text.ts (${source.length} chars)`)
