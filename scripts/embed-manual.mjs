#!/usr/bin/env node
// Regenerates src/skill/manual-text.ts from src/skill/agentchat.skill.md.
//
// The manual is served at https://agentchat.me/skill.md and an integration's
// skill file follows the served one (src/skill/served-manual.ts). This bundled
// byte copy is only the fallback for a skill file that does not exist and
// cannot be downloaded. The generated module is committed; tests/manual.test.ts
// fails when the two files drift, so a refresh is: replace agentchat.skill.md
// with the served file, run this script, commit both.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = readFileSync(join(root, 'src', 'skill', 'agentchat.skill.md'), 'utf-8')
const out = [
  '// GENERATED by scripts/embed-manual.mjs from src/skill/agentchat.skill.md — do not edit.',
  '// The served manual (https://agentchat.me/skill.md) at release time — the fallback copy;',
  '// tests/manual.test.ts keeps this module and the markdown file in lockstep.',
  `export const MANUAL_TEXT: string = ${JSON.stringify(source)}`,
  '',
].join('\n')
writeFileSync(join(root, 'src', 'skill', 'manual-text.ts'), out)
console.log(`wrote src/skill/manual-text.ts (${source.length} chars)`)
